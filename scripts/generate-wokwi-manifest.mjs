import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageRoot = join(projectRoot, 'node_modules', '@wokwi', 'elements');
const esmRoot = join(packageRoot, 'dist', 'esm');
const outputPath = join(projectRoot, 'src', 'generated', 'wokwi-elements-manifest.js');
const checkOnly = process.argv.includes('--check');

function propertyType(typeSource = '') {
    const source = typeSource.trim();
    if (source.includes('[]') || source.includes('{') || source.includes('=>')) return 'unknown';
    if (source === 'boolean') return 'boolean';
    if (source === 'number') return 'number';
    if (source === 'string') return 'string';
    if (/\bboolean\b/.test(source) && !/\b(string|number)\b/.test(source)) return 'boolean';
    if (/\bnumber\b/.test(source) && !/\b(string|boolean)\b/.test(source)) return 'number';
    if (/\bstring\b/.test(source) && !/\b(number|boolean)\b/.test(source)) return 'string';
    return 'unknown';
}

function literalValue(source) {
    const value = source.trim();
    if (value === 'true') return { found: true, value: true };
    if (value === 'false') return { found: true, value: false };
    if (value === 'null') return { found: true, value: null };
    if (/^-?(?:\d+\.?\d*|\.\d+)(?:e[+-]?\d+)?$/i.test(value)) {
        return { found: true, value: Number(value) };
    }
    const stringMatch = value.match(/^(['"])([\s\S]*)\1$/);
    if (stringMatch) {
        try {
            return { found: true, value: JSON.parse(`"${stringMatch[2]
                .replace(/\\/g, '\\\\')
                .replace(/"/g, '\\"')}"`) };
        } catch {
            return { found: true, value: stringMatch[2] };
        }
    }
    return { found: false };
}

function extractProperties(jsSource, declarationSource, className) {
    const decorated = new Set();
    const propertyPattern = new RegExp(
        `property(?:\\([^)]*\\))?\\s*\\]\\s*,\\s*${className}\\.prototype,\\s*["']([^"']+)["']`,
        'g',
    );
    for (const match of jsSource.matchAll(propertyPattern)) decorated.add(match[1]);

    const types = new Map();
    for (const line of declarationSource.split(/\r?\n/)) {
        const match = line.match(/^\s{4}([A-Za-z_$][\w$]*)[!?]?:\s*([^;]+);\s*$/);
        if (match) types.set(match[1], match[2]);
    }

    return [...decorated].sort().map(name => {
        const descriptor = { name, type: propertyType(types.get(name)) };
        const assignment = jsSource.match(new RegExp(`this\\.${name.replace(/[$]/g, '\\$&')}\\s*=\\s*([^;]+);`));
        const parsed = assignment ? literalValue(assignment[1]) : { found: false };
        if (parsed.found) descriptor.default = parsed.value;
        return descriptor;
    });
}

async function generateManifest() {
    const packageJson = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8'));
    const indexSource = await readFile(join(esmRoot, 'index.d.ts'), 'utf8');
    const modules = [...indexSource.matchAll(/^export\s+\{[^}]+\}\s+from\s+['"]\.\/(.+-element)['"];?$/gm)]
        .map(match => match[1]);
    const elements = [];

    for (const moduleName of modules) {
        const [jsSource, declarationSource] = await Promise.all([
            readFile(join(esmRoot, `${moduleName}.js`), 'utf8'),
            readFile(join(esmRoot, `${moduleName}.d.ts`), 'utf8'),
        ]);
        const tag = jsSource.match(/customElement\(['"]([^'"]+)['"]\)/)?.[1];
        const className = declarationSource.match(/export\s+declare\s+class\s+(\w+)/)?.[1];
        if (!tag || !className) continue;
        elements.push({
            tag,
            className,
            module: moduleName,
            properties: extractProperties(jsSource, declarationSource, className),
        });
    }

    elements.sort((left, right) => left.tag.localeCompare(right.tag));
    return {
        package: packageJson.name,
        version: packageJson.version,
        generatedFrom: 'dist/esm/index.d.ts',
        elements,
    };
}

function sourceFor(manifest) {
    return `// Generated by scripts/generate-wokwi-manifest.mjs. Do not edit by hand.\n` +
        `export const WOKWI_ELEMENTS_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n\n` +
        `export const WOKWI_ELEMENT_BY_TAG = Object.freeze(\n` +
        `    Object.fromEntries(WOKWI_ELEMENTS_MANIFEST.elements.map(element => [element.tag, element]))\n` +
        `);\n`;
}

const nextSource = sourceFor(await generateManifest());
if (checkOnly) {
    const currentSource = await readFile(outputPath, 'utf8').catch(() => '');
    if (currentSource !== nextSource) {
        console.error('Wokwi manifest is stale. Run npm run components:generate.');
        process.exitCode = 1;
    }
} else {
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, nextSource, 'utf8');
}
